#!/usr/bin/env python3
"""Generate the board demo's golden constants from the bit-exact Python model.

The demo firmware (firmware/nexus32_demo.S) synthesizes its input block on
the CPU with the same recurrence defined here, runs it through every FIR
architecture, and compares a rolling checksum of the 1024 results with the
constants this script derives from golden_model.fir_q16. The checksum is the
independent oracle: it never comes from the RTL.

Usage: python3 scripts/gen_demo_expected.py <output.inc>
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from golden_model.fir_q16 import fir_block_q16_16  # noqa: E402

MASK32 = 0xFFFF_FFFF
SAMPLES = 1024
SEED = 0x0001_2345
STEP = 0x0003_0001
COEFF0 = 0x0000_8000       # +0.5 in Q16.16
COEFF_STEP = 0x0000_0800   # 1/32 in Q16.16
COEFF_WORDS = 32
TAP_COUNTS = (4, 8, 16, 32)


def to_int32(value: int) -> int:
    value &= MASK32
    return value - (1 << 32) if value & 0x8000_0000 else value


def demo_samples() -> list[int]:
    """s = s*5 + STEP (mod 2^32); sample = int32(s) >> 12 (arithmetic)."""
    state = SEED
    samples = []
    for _ in range(SAMPLES):
        state = (state * 5 + STEP) & MASK32
        samples.append(to_int32(state) >> 12)
    return samples


def demo_coefficients() -> list[int]:
    """coefficient[k] = COEFF0 - k*COEFF_STEP for the 32 coefficient words."""
    return [to_int32(COEFF0 - k * COEFF_STEP) for k in range(COEFF_WORDS)]


def rolling_checksum(results: list[int]) -> int:
    """checksum = rotl32(checksum, 5) ^ uint32(result), starting from 0."""
    checksum = 0
    for result in results:
        checksum = (((checksum << 5) | (checksum >> 27)) & MASK32) ^ (result & MASK32)
    return checksum


def expected_checksums() -> dict[int, int]:
    samples = demo_samples()
    coefficients = demo_coefficients()
    return {
        taps: rolling_checksum(fir_block_q16_16(samples, coefficients[:taps]))
        for taps in TAP_COUNTS
    }


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    checksums = expected_checksums()
    lines = [
        "/* Generated by scripts/gen_demo_expected.py from golden_model/fir_q16.py. */",
        "/* Do not edit: regenerate with the build script. */",
        f".equ DEMO_SAMPLES, {SAMPLES}",
        f".equ DEMO_SEED, 0x{SEED:08x}",
        f".equ DEMO_STEP, 0x{STEP:08x}",
        f".equ DEMO_COEFF0, 0x{COEFF0:08x}",
        f".equ DEMO_COEFF_STEP, 0x{COEFF_STEP:08x}",
        f".equ DEMO_COEFF_WORDS, {COEFF_WORDS}",
    ]
    lines += [f".equ EXPECT_CHK_T{taps}, 0x{value:08x}" for taps, value in checksums.items()]
    output = Path(argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    for taps, value in checksums.items():
        print(f"demo expected checksum TAP_COUNT={taps}: 0x{value:08x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
